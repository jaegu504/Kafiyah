// --- Logika Kontrol Flashcard ---
let currentQuestions = [];
let currentIndex = -1;
let currentChapter = "";
let displayedIndices = [];

const questionTextElement = document.getElementById('questionText');
const answerTextElement = document.getElementById('answerText');
const answerContainer = document.getElementById('answerContainer');
const showAnswerBtn = document.getElementById('showAnswerBtn');
const nextQuestionBtn = document.getElementById('nextQuestionBtn');
const chapterBtns = document.querySelectorAll('.chapter-btn');
const darkModeToggle = document.getElementById('darkModeToggle');
const sidebar = document.getElementById('sidebar');
const hamburgerBtn = document.getElementById('hamburgerBtn');

// Filter Bab
chapterBtns.forEach(btn => {
    btn.addEventListener('click', () => {
        const chapter = btn.getAttribute('data-chapter');
        selectChapter(chapter);
        if (window.innerWidth <= 768) sidebar.classList.remove('open');
    });
});

function selectChapter(chapter) {
    currentChapter = chapter;
    if (chapter === 'all') {
        currentQuestions = [...questions];
    } else {
        currentQuestions = questions.filter(q => q.chapter === chapter);
    }
    displayedIndices = [];
    nextQuestion();
    showAnswerBtn.disabled = false;
    nextQuestionBtn.disabled = false;
}

function nextQuestion() {
    if (currentQuestions.length === 0) return;
    
    if (displayedIndices.length === currentQuestions.length) {
        questionTextElement.textContent = "بوندە پك چوق سؤال بيتدی! باشقە باب سچڭز.";
        answerContainer.style.display = 'none';
        showAnswerBtn.disabled = true;
        nextQuestionBtn.disabled = true;
        return;
    }

    let randomIndex;
    do {
        randomIndex = Math.floor(Math.random() * currentQuestions.length);
    } while (displayedIndices.includes(randomIndex));

    currentIndex = randomIndex;
    displayedIndices.push(currentIndex);

    questionTextElement.textContent = currentQuestions[currentIndex].question;
    answerTextElement.textContent = currentQuestions[currentIndex].answer;
    answerContainer.style.display = 'none';
    showAnswerBtn.textContent = "جوابی كور";
}

showAnswerBtn.addEventListener('click', () => {
    if (answerContainer.style.display === 'none') {
        answerContainer.style.display = 'block';
        showAnswerBtn.textContent = "جوابی كيزله";
    } else {
        answerContainer.style.display = 'none';
        showAnswerBtn.textContent = "جوابی كور";
    }
});

nextQuestionBtn.addEventListener('click', nextQuestion);

// Dark Mode
darkModeToggle.addEventListener('click', () => {
    const isDark = document.documentElement.getAttribute('data-theme') === 'dark';
    document.documentElement.setAttribute('data-theme', isDark ? 'light' : 'dark');
    darkModeToggle.textContent = isDark ? "مظلم وضع" : "آيدينلق وضع";
});

// Hamburger
hamburgerBtn.addEventListener('click', () => sidebar.classList.toggle('open'));
